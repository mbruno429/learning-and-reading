#!/usr/bin/env node
/* Writes www/sw.js: the offline cache list for the hosted version. Run after changing anything under www/
   (the GitHub Pages workflow runs it too, so the published copy is always current). */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const WWW = path.join(__dirname, '..', 'app', 'src', 'main', 'assets', 'www');
const files = [];
(function walk(dir, rel) {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name), r = rel ? rel + '/' + name : name;
    if (fs.statSync(full).isDirectory()) walk(full, r);
    else if (r !== 'sw.js' && name[0] !== '.' && !/\.txt$/.test(name)) files.push(r);
  }
})(WWW, '');
const hash = crypto.createHash('sha1');
files.forEach(f => { hash.update(f); hash.update(fs.readFileSync(path.join(WWW, f))); });
const version = hash.digest('hex').slice(0, 12);
const sw = `/* Generated by tools/make-sw.js. Do not edit. Offline cache for the hosted version of Reading Quest. */
const CACHE = 'rq-${version}';
const FILES = ${JSON.stringify(['./'].concat(files), null, 1)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.indexOf('rq-') === 0 && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).catch(() => caches.match('./'))));
});
`;
fs.writeFileSync(path.join(WWW, 'sw.js'), sw);
console.log('sw.js: ' + files.length + ' files, version ' + version);
