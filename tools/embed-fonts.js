#!/usr/bin/env node
/* Writes css/fonts.css with the fonts embedded as data: URIs, so they load the same way on every WebView. */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, 'fonts');
const faces = [
  ['Lexend', 400, 'lexend-latin-400-normal.woff2'], ['Lexend', 600, 'lexend-latin-600-normal.woff2'], ['Lexend', 700, 'lexend-latin-700-normal.woff2'],
  ['Baloo 2', 700, 'baloo-2-latin-700-normal.woff2'], ['Baloo 2', 800, 'baloo-2-latin-800-normal.woff2']
];
const css = '/* Generated by tools/embed-fonts.js. Lexend and Baloo 2, SIL Open Font License (see ../fonts/). */\n' + faces.map(([fam, w, file]) =>
  `@font-face { font-family: '${fam}'; font-weight: ${w}; font-display: swap; src: url(data:font/woff2;base64,${fs.readFileSync(path.join(dir, file)).toString('base64')}) format('woff2'); }`).join('\n') + '\n';
fs.writeFileSync(path.join(__dirname, '..', 'app', 'src', 'main', 'assets', 'www', 'css', 'fonts.css'), css);
console.log('fonts.css', css.length, 'bytes');
